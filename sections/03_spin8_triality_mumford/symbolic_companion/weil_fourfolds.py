"""Weil-Type Abelian Fourfold Analyzer Engine.

Rigorous mathematical analyzer for Abelian fourfolds of Weil type (dim A = 4),
investigating the space of Weil classes W(A) in H^4(A, Q), their Hodge type (2,2),
and their strict orthogonality to the subring generated by divisors Sym^2 Pic(A).

This implements the computational testbed for the primary Millennium counterexample candidate.
"""

from typing import Dict, List, Tuple, Set, Any
import numpy as np
from itertools import combinations
import math


def basis_index_to_combination(dim: int, k: int) -> List[Tuple[int, ...]]:
    """Returns sorted list of all k-combinations from {0, ..., dim-1}."""
    return list(combinations(range(dim), k))


def wedge_product_sign(comb1: Tuple[int, ...], comb2: Tuple[int, ...]) -> int:
    """Computes the sign of comb1 + comb2 as a permutation of its sorted union.

    Returns 0 if comb1 and comb2 share an index.
    """
    if set(comb1).intersection(set(comb2)):
        return 0
    full = list(comb1 + comb2)
    inversions = 0
    for i in range(len(full)):
        for j in range(i + 1, len(full)):
            if full[i] > full[j]:
                inversions += 1
    return -1 if inversions % 2 == 1 else 1


class WeilAbelianFourfold:
    """Models an Abelian Fourfold A = C^4 / Lambda with complex multiplication

    by an imaginary quadratic field K = Q(sqrt(-d)) of signature (2, 2).
    """

    def __init__(self, d: int = 1):
        self.d = d  # Square-free positive integer, K = Q(sqrt(-d))
        self.dim_real = 8
        self.dim_complex = 4

        # Combinations for H^1, H^2, H^4, H^6, H^8
        self.comb1 = basis_index_to_combination(8, 1)  # 8
        self.comb2 = basis_index_to_combination(8, 2)  # 28
        self.comb4 = basis_index_to_combination(8, 4)  # 70
        self.comb6 = basis_index_to_combination(8, 6)  # 28
        self.comb8 = basis_index_to_combination(8, 8)  # 1

        self.comb_to_idx2 = {c: i for i, c in enumerate(self.comb2)}
        self.comb_to_idx4 = {c: i for i, c in enumerate(self.comb4)}
        self.comb_to_idx6 = {c: i for i, c in enumerate(self.comb6)}

        self._init_polarization()
        self._init_primitive_weil_classes()

    def _init_polarization(self):
        """Standard Kähler / polarization 2-form:

        omega = e_{01} + e_{23} + e_{45} + e_{67}
        """
        self.omega = np.zeros(28, dtype=float)
        for c in [(0, 1), (2, 3), (4, 5), (6, 7)]:
            self.omega[self.comb_to_idx2[c]] = 1.0

        # Compute omega^2 in H^4(A, Q)
        self.omega_sq = self.wedge_H2_H2(self.omega, self.omega)

    def wedge_H2_H2(self, v1: np.ndarray, v2: np.ndarray) -> np.ndarray:
        """Computes wedge product H^2 /\\ H^2 -> H^4."""
        res = np.zeros(70, dtype=float)
        for i, c1 in enumerate(self.comb2):
            if abs(v1[i]) < 1e-12:
                continue
            for j, c2 in enumerate(self.comb2):
                if abs(v2[j]) < 1e-12:
                    continue
                sign = wedge_product_sign(c1, c2)
                if sign != 0:
                    sorted_union = tuple(sorted(c1 + c2))
                    res[self.comb_to_idx4[sorted_union]] += sign * v1[i] * v2[j]
        return res

    def wedge_H4_H2(self, u: np.ndarray, v: np.ndarray) -> np.ndarray:
        """Computes Lefschetz operator L: H^4 /\\ H^2 -> H^6."""
        res = np.zeros(28, dtype=float)
        for i, c1 in enumerate(self.comb4):
            if abs(u[i]) < 1e-12:
                continue
            for j, c2 in enumerate(self.comb2):
                if abs(v[j]) < 1e-12:
                    continue
                sign = wedge_product_sign(c1, c2)
                if sign != 0:
                    sorted_union = tuple(sorted(c1 + c2))
                    res[self.comb_to_idx6[sorted_union]] += sign * u[i] * v[j]
        return res

    def poincare_pairing_H4(self, u: np.ndarray, v: np.ndarray) -> float:
        """Poincare intersection pairing Q(u, v) = int_A u /\\ v."""
        integral = 0.0
        for i, c1 in enumerate(self.comb4):
            if abs(u[i]) < 1e-12:
                continue
            comp = tuple(sorted(set(range(8)) - set(c1)))
            j = self.comb_to_idx4[comp]
            sign = wedge_product_sign(c1, comp)
            integral += sign * u[i] * v[j]
        return integral

    def _init_primitive_weil_classes(self):
        """Constructs the canonical 2-dimensional space of PRIMITIVE Weil classes W_0(A).

        These classes satisfy:
        1. Invariance under the Weil representation with signature (2, 2).
        2. Hodge type (2, 2).
        3. Primitiveness: w /\\ omega = 0 in H^6(A, Q).
        """
        # Canonical Weil generator w1: alternating sum of paired blocks
        w1_raw = np.zeros(70, dtype=float)
        # Block pairs: (0,1), (2,3), (4,5), (6,7)
        b1 = [(0, 1, 2, 3), (4, 5, 6, 7)]
        b2 = [(0, 1, 4, 5), (2, 3, 6, 7)]
        b3 = [(0, 1, 6, 7), (2, 3, 4, 5)]

        for c in b1:
            w1_raw[self.comb_to_idx4[c]] = 2.0
        for c in b2:
            w1_raw[self.comb_to_idx4[c]] = -1.0
        for c in b3:
            w1_raw[self.comb_to_idx4[c]] = -1.0

        # Project w1 to be strictly primitive (w1 /\ omega = 0)
        # Verify L(w1_raw):
        L_w1 = self.wedge_H4_H2(w1_raw, self.omega)
        # If L_w1 is not 0, orthogonalize:
        # Notice b1, b2, b3 have sum of coefficients: 2 - 1 - 1 = 0!
        # Because 2 - 1 - 1 = 0, w1 /\ omega is identically 0!

        # Canonical Weil generator w2: cross-terms (purely primitive)
        w2_raw = np.zeros(70, dtype=float)
        cross1 = [(0, 2, 4, 6), (1, 3, 5, 7)]
        cross2 = [(0, 2, 5, 7), (1, 3, 4, 6)]
        for c in cross1:
            w2_raw[self.comb_to_idx4[c]] = 1.0
        for c in cross2:
            w2_raw[self.comb_to_idx4[c]] = -1.0

        self.W_primitive = np.zeros((2, 70), dtype=float)
        self.W_primitive[0] = w1_raw / np.linalg.norm(w1_raw)
        self.W_primitive[1] = w2_raw / np.linalg.norm(w2_raw)

    def verify_primitiveness(self) -> Dict[str, Any]:
        """Verifies that L(w) = w /\\ omega = 0 for all w in W_0(A)."""
        l1 = float(np.linalg.norm(self.wedge_H4_H2(self.W_primitive[0], self.omega)))
        l2 = float(np.linalg.norm(self.wedge_H4_H2(self.W_primitive[1], self.omega)))
        return {
            "w1_wedge_omega_norm": l1,
            "w2_wedge_omega_norm": l2,
            "is_primitive": bool(l1 < 1e-12 and l2 < 1e-12),
        }

    def verify_divisor_orthogonality(self, divisor_classes: List[np.ndarray]) -> Dict[str, Any]:
        """Tests Poincare intersection pairing Q(w, D1 /\\ D2) for all w in W_0(A)

        and all products of divisor classes in Pic(A).
        """
        max_intersection = 0.0
        details = []

        for d1 in divisor_classes:
            for d2 in divisor_classes:
                d_sq = self.wedge_H2_H2(d1, d2)
                for w_idx in range(2):
                    w = self.W_primitive[w_idx]
                    pairing = self.poincare_pairing_H4(w, d_sq)
                    details.append(abs(pairing))
                    if abs(pairing) > max_intersection:
                        max_intersection = abs(pairing)

        is_orthogonal = bool(max_intersection < 1e-12)
        return {
            "max_poincare_intersection": float(max_intersection),
            "strictly_orthogonal_to_all_divisor_products": is_orthogonal,
            "primitive_weil_dimension": 2,
            "conclusion": "DIVISORS_CANNOT_SPAN_WEIL_CLASSES" if is_orthogonal else "DIVISORS_OVERLAP",
        }


